use embed_manifest::manifest::{DpiAwareness, ExecutionLevel};
use embed_manifest::{embed_manifest, new_manifest};

fn main() {
    if std::env::var_os("CARGO_CFG_WINDOWS").is_some() {
        // Per-monitor-v2 DPI awareness, Common Controls v6 (visual styles), no UAC elevation.
        // The manifest version comes from the Cargo.toml version (embed-manifest reads it).
        let manifest = new_manifest("SgCap.App")
            .dpi_awareness(DpiAwareness::PerMonitorV2)
            .requested_execution_level(ExecutionLevel::AsInvoker);
        embed_manifest(manifest).expect("unable to embed manifest");
        write_version_header();
        // Application icon (resources/sgcap.ico) and version information, compiled with the
        // SDK resource compiler. OUT_DIR, where sgcap_version.h is written, is on its include path.
        embed_resource::compile("resources/sgcap.rc", embed_resource::NONE)
            .manifest_required()
            .expect("unable to compile resources/sgcap.rc");
    }
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=resources/sgcap.rc");
    println!("cargo:rerun-if-changed=resources/sgcap.ico");
}

/// Writes the Cargo.toml version (CalVer YYYY.M.MICRO) for the VERSIONINFO resource. Windows
/// stores each part of a binary version in 16 bits, so a part above 65535 fails the build.
fn write_version_header() {
    let part = |name: &str| -> u16 {
        let value = std::env::var(name).expect("Cargo sets the package version");
        value.parse().unwrap_or_else(|_| panic!("{name}={value} does not fit a Windows version (0-65535)"))
    };
    let (major, minor, patch) = (
        part("CARGO_PKG_VERSION_MAJOR"),
        part("CARGO_PKG_VERSION_MINOR"),
        part("CARGO_PKG_VERSION_PATCH"),
    );
    let version = std::env::var("CARGO_PKG_VERSION").unwrap();
    let header = format!(
        "// Generated by build.rs from the Cargo.toml version.\n\
         #define SGCAP_VERSION_BIN {major},{minor},{patch},0\n\
         #define SGCAP_VERSION_STR \"{version}\"\n"
    );
    let out_dir = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("sgcap_version.h"), header).expect("unable to write sgcap_version.h");
}
